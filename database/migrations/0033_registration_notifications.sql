-- Сповіщення адмінам про нову заявку на реєстрацію — перемикач "чи хочу я
-- (адмін) отримувати особисте DM щоразу, коли хтось подає заявку".
--
-- Живе в уже існуючій user_notification_settings (0032), а не в новій
-- таблиці: той самий шаблон "один рядок на користувача, набір boolean
-- перемикачів", і додавати окрему таблицю заради одного стовпця було б
-- невиправданим дублюванням. Функціонально стосується лише адмінів
-- (розсилка приєднує admin_users), але зберігання спільне з рештою
-- особистих налаштувань — той самий фасад GET/PATCH /api/me/notifications.
--
-- За замовчуванням false: жоден адмін не отримує сповіщень, поки сам не
-- увімкне перемикач у розділі "Заявки" адмін-панелі.
--
-- Міграція суто additive: жодна існуюча таблиця чи колонка не
-- змінюється, тож застосування на живій базі безпечне.

alter table public.user_notification_settings
  add column if not exists notify_new_registrations boolean not null default false;
